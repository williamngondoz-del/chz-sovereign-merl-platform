function makeSeedEvidence(name: string, sizeKb: number, mimeType: string, path: string, uploadedAt: string) {
  return {
    name,
    sizeKb,
    mimeType,
    sha256: sha256HexSync(`chz-vault-seed|${name}|${sizeKb}|${path}`),
    vaultPath: path,
    uploadedAt,
    hashedFromBytes: true,
  };
}

